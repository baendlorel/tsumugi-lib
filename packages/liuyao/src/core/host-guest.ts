import type { 六爻卦 } from '../classes/hexagram.js';
`
世应章
乾为天：世在六爻；天风姤：世在初爻；天山遁：世在二爻；火地晋：世退在四爻；
天地否：世在三爻；风地观：世在四爻；山地剥：世在五爻；火天大有：世退在三爻；
隔世爻两位，即是应爻。余卦仿此。
`;

const 世位 = [5, 0, 1, 2, 3, 4, 3, 2] as const;

/**
 * 应位满足公式`(世位 + 3) % 6`
 */
const 应位 = [2, 3, 4, 5, 0, 1, 0, 5] as const;

/**
 * @see 《增删卜易·世应章》
 */
export function 装世应(hexagram: 六爻卦): { 世: 0 | 1 | 2 | 3 | 4 | 5; 应: 0 | 1 | 2 | 3 | 4 | 5 } {
  return {
    世: 世位[hexagram.八宫卦位],
    应: 应位[hexagram.八宫卦位],
  };
}
